// Finds a dsh CLI and prepares an isolated DSH_HOME for a run.
//
// A fresh install has no cliPath, and a GUI-launched host inherits no shell
// env, so DSH_BENCH_CLI is usually absent. Without this, the first run on any
// other machine just fails with "dsh CLI not found".
//
// The CLI runner is injected so this can be tested without spawning anything.

import { mkdir, copyFile, writeFile, readFile, access } from 'node:fs/promises'
import { constants } from 'node:fs'
import { join, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'

/** Default isolated home, relative to the workspace, when config leaves it empty. */
export const DEFAULT_HOME_DIR = '.agent-bench/home'
/** Profile the benchmark creates inside that home. */
export const DEFAULT_PROFILE = 'headless'

async function exists(p) {
  try {
    await access(p, constants.F_OK)
    return true
  } catch {
    return false
  }
}

/**
 * Locate the dsh CLI entry.
 *
 * Order: explicit config, then DSH_BENCH_CLI, then a `dsh` executable on PATH.
 * Returns `{ kind: 'node', path }` when the path is a JS entry that must run
 * under node, or `{ kind: 'command', command: 'dsh' }` for a PATH executable.
 */
export function resolveCli({ explicit, env = process.env, probe = probeCommand } = {}) {
  for (const candidate of [explicit, env.DSH_BENCH_CLI]) {
    if (typeof candidate === 'string' && candidate.trim() !== '') {
      return { kind: 'node', path: resolve(candidate.trim()) }
    }
  }
  if (probe('dsh')) return { kind: 'command', command: 'dsh' }
  return null
}

/** True when a command name resolves on PATH. */
export function probeCommand(name) {
  const finder = process.platform === 'win32' ? 'where' : 'which'
  const r = spawnSync(finder, [name], { encoding: 'utf8', windowsHide: true })
  return r.status === 0 && String(r.stdout ?? '').trim() !== ''
}

/**
 * Decide which auth overlay the isolated home needs.
 *
 * dsh-base mounts the api-key provider (`deepseek-official`). A user signed in
 * with the DeepSeek ACCOUNT (device grant) has no API key, so the account
 * provider must be mounted instead or every run dies with MISSING_CREDENTIAL.
 * API-key users need no overlay: the key travels in the inherited environment.
 */
export function pickAuthMode(credentialsText) {
  if (typeof credentialsText === 'string' && credentialsText.includes('deepseek-account-platform')) {
    return 'account'
  }
  return 'passthrough'
}

/** Render the overlay YAML for an auth mode. */
export function renderOverlay(mode) {
  if (mode !== 'account') return null
  return [
    '# Generated by dsh-agent-bench: run the agent with the DeepSeek ACCOUNT',
    '# provider instead of the api-key route that dsh-base mounts by default.',
    '- id: llm-deepseek',
    '  disabled: true',
    '- id: agent-default-model',
    '  config:',
    '    provider: deepseek-account',
    '    model: deepseek-flash',
    '- insert:',
    '    - id: llm-deepseek-account',
    "      name: '@deepseek-ai/dsh-llm-deepseek-account'",
    '    - id: deepseek-account',
    "      name: '@deepseek-ai/dsh-deepseek-account-platform'",
    '',
  ].join('\n')
}

/**
 * Prepare an isolated DSH_HOME for benchmark runs.
 *
 * Idempotent: an existing home keeps its credentials and profile, so repeated
 * runs do not re-authenticate or re-initialise.
 *
 * @returns {{home:string, profile:string, overlayPath:string|null, cliArgs:string[], mode:string, notes:string[]}}
 */
export async function prepareBenchHome({
  home,
  realHome,
  cli,
  profile = DEFAULT_PROFILE,
  runCli,
  notes = [],
}) {
  const absHome = resolve(home)
  await mkdir(absHome, { recursive: true })

  // 1. Reuse the user's credentials, reading them without ever writing back.
  const credSrc = join(resolve(realHome), '.credentials.yaml')
  const credDst = join(absHome, '.credentials.yaml')
  let credentialsText = ''
  if (await exists(credSrc)) {
    if (!(await exists(credDst))) {
      await copyFile(credSrc, credDst)
      notes.push(`copied credentials from ${credSrc} (read-only reuse)`)
    }
    credentialsText = await readFile(credDst, 'utf8')
  } else {
    notes.push(`no credentials at ${credSrc}; falling back to environment (e.g. DEEPSEEK_API_KEY)`)
  }

  // 2. Write the auth overlay the isolated home needs, if any.
  const mode = pickAuthMode(credentialsText)
  const overlayYaml = renderOverlay(mode)
  let overlayPath = null
  if (overlayYaml !== null) {
    overlayPath = join(absHome, 'bench-overlay.yml')
    await writeFile(overlayPath, overlayYaml, 'utf8')
    notes.push(`auth mode: account (overlay at ${overlayPath})`)
  } else {
    notes.push('auth mode: passthrough (api key from environment)')
  }

  // 3. Make sure the profile composes in this home.
  //
  // A shipped template (e.g. "headless") composes straight from the DSH
  // installation and must NOT be created as a custom profile -- dsh rejects
  // `--from-default-profile headless --profile headless` with "profile is
  // shipped and cannot be a custom profile target". So probe first and only
  // fall back to initialising when the name is genuinely absent.
  const manifest = join(absHome, 'profiles', profile, 'package.json')
  const probe = await runCli(cli, ['--profile', profile, '--dump-config'], absHome)
  if (probe.status !== 0) {
    const init = await runCli(
      cli,
      ['--from-default-profile', profile, '--profile', profile, '--dump-config'],
      absHome,
    )
    if (init.status !== 0 && !(await exists(manifest))) {
      throw new Error(
        `profile "${profile}" is not usable in ${absHome}: `
          + `${(init.stderr || init.stdout || probe.stderr || probe.stdout || `exit ${init.status}`).slice(0, 400)}`,
      )
    }
    notes.push(`initialised profile ${profile}`)
  } else {
    notes.push(`profile ${profile} composes as-is (shipped template or existing)`)
  }

  const cliArgs = ['--profile', profile]
  if (overlayPath !== null) cliArgs.push('--patch', overlayPath)

  return { home: absHome, profile, overlayPath, cliArgs, mode, notes }
}

/**
 * Spawn the CLI with the isolated home. `cli` comes from resolveCli().
 * Returns the raw spawnSync result plus a normalised exit code.
 */
export function runCli(cli, args, cwd, { timeout = 180_000, home, env = process.env } = {}) {
  if (cli === null || cli === undefined) {
    return { status: 1, stdout: '', stderr: 'dsh CLI not resolved' }
  }
  const childEnv = { ...env }
  if (home) childEnv.DSH_HOME = home

  const opts = { cwd, env: childEnv, encoding: 'utf8', timeout, windowsHide: true }
  const r =
    cli.kind === 'command'
      ? spawnSync(cli.command, args, { ...opts, shell: process.platform === 'win32' })
      : spawnSync(process.execPath, [cli.path, ...args], opts)
  return { status: r.status, stdout: r.stdout ?? '', stderr: r.stderr ?? '' }
}

/** Build the spawn argv for one benchmark case under a resolved CLI. */
export function buildSpawn(cli, cliArgs, task) {
  if (cli.kind === 'command') {
    return { command: cli.command, args: [...cliArgs, task], shell: process.platform === 'win32' }
  }
  return { command: process.execPath, args: [cli.path, ...cliArgs, task], shell: false }
}
